#!/usr/bin/env node
/**
 * Extracts the *Bold* weight of the Phosphor icons we use into a tree-shakeable module.
 * The npm components ship all six weights per icon (~2.2 KB each); we only ever render Bold
 * (CLAUDE.md §6.6), so the generated module keeps the player bundle small.
 *
 * Usage: node scripts/build-icons.mjs  →  src/components/ui/icon-data.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

