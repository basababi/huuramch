const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(join(here, '..', 'package.json'));
const pkgDir = dirname(require.resolve('@phosphor-icons/react/package.json'));
const { version } = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));

/** Pull the `["bold", …]` entry out of a defs module and list its createElement calls. */
function boldElements(phosphorName) {
  const src = readFileSync(join(pkgDir, 'dist', 'defs', `${phosphorName}.es.js`), 'utf8');
  const start = src.indexOf('"bold"');
  if (start === -1) throw new Error(`${phosphorName}: no bold weight`);
  const end = src.indexOf('\n  [\n', start);
  const chunk = src.slice(start, end === -1 ? undefined : end);
  const elements = [];
  const re =
    /createElement\(\s*"(path|circle|rect|line|polyline|polygon|ellipse)",\s*(\{[\s\S]*?\})\s*\)/g;
  for (const match of chunk.matchAll(re)) {
    const attrs = Function(`"use strict"; return (${match[2]});`)();
    elements.push([match[1], attrs]);
  }
  if (elements.length === 0) throw new Error(`${phosphorName}: bold weight has no shapes`);
  return elements;
}

const lines = [
  '// Generated by scripts/build-icons.mjs — do not edit by hand.',
  `// Phosphor Icons v${version} (MIT, https://phosphoricons.com), Bold weight only.`,
  '',
  "import type { IconData } from './icon';",
  '',
];
for (const [name, phosphorName] of Object.entries(ICONS)) {
  const data = JSON.stringify(boldElements(phosphorName));
  lines.push(`export const ${name}: IconData = ${data};`);
}
lines.push('');

const out = join(here, '..', 'src', 'components', 'ui', 'icon-data.ts');
writeFileSync(out, lines.join('\n'));
console.warn(`icon-data.ts: ${Object.keys(ICONS).length} icons written`);
