  qr: 'QrCode',
  question: 'Question',
  replay: 'ArrowCounterClockwise',
  sealCheck: 'SealCheck',
  signIn: 'SignIn',
  signOut: 'SignOut',
  skip: 'SkipForward',
  speaker: 'SpeakerHigh',
  speakerOff: 'SpeakerSlash',
